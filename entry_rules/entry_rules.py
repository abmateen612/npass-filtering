# ---------- SMARTS patterns (substructure search patterns) ----------
# PRIMARY AMINE: -NH2 on a saturated (sp3) carbon. The "!$(...)" parts exclude
# look-alikes that are not basic amines: amides, anilines, sulfonamides,
# hydrazines and hydroxylamines.
PRIMARY_AMINE = Chem.MolFromSmarts(
    "[NX3;H2;!$(N-C=[O,S,N]);!$(N-a);!$(N-S(=O));!$(N-N);!$(N-O)][CX4]")

# Other basic nitrogens (only used for the optional "relaxed" version)
SECONDARY_AMINE = Chem.MolFromSmarts(
    "[NX3;H1;!$(N-C=[O,S,N]);!$(N-a);!$(N-S(=O));!$(N-N);!$(N-O)]([CX4])[CX4]")
TERTIARY_AMINE = Chem.MolFromSmarts(
    "[NX3;H0;!$(N-C=[O,S,N]);!$(N-a);!$(N-S(=O));!$(N-N);!$(N-O)]([CX4])([CX4])[CX4]")
AMIDINE_GUANIDINE = Chem.MolFromSmarts("[NX3;!$(N-C=O)]-C(=[NX2;!$(N-C=O)])")


def largest_fragment(mol):
    """Remove salts/counter-ions by keeping the biggest fragment."""
    frags = Chem.GetMolFrags(mol, asMols=True)
    return max(frags, key=lambda m: m.GetNumHeavyAtoms())


def calc_globularity(mol, seed=42):
    """
    Globularity = how ball-like the 3D shape is (0 = flat/rod, 1 = sphere).
    Build a 3D structure, take heavy-atom coordinates, compute the covariance
    matrix, and return smallest eigenvalue / largest eigenvalue.
    """
    molH = Chem.AddHs(mol)                       # hydrogens needed for good 3D geometry
    params = AllChem.ETKDGv3()                   # modern 3D embedding method
    params.randomSeed = seed                     # fixed seed = reproducible
    params.maxIterations = 200                   # stops hopeless molecules from hanging

    if AllChem.EmbedMolecule(molH, params) != 0: # 0 = success
        params.useRandomCoords = True            # fallback for difficult molecules
        if AllChem.EmbedMolecule(molH, params) != 0:
            return np.nan

    try:
        AllChem.MMFFOptimizeMolecule(molH, maxIters=500)   # relax geometry
    except Exception:
        pass

    conf = molH.GetConformer()
    idx = [a.GetIdx() for a in molH.GetAtoms() if a.GetAtomicNum() > 1]  # heavy atoms
    coords = np.array([list(conf.GetAtomPosition(i)) for i in idx])
    if len(coords) < 4:
        return np.nan

    eig = np.sort(np.linalg.eigvalsh(np.cov(coords.T)))    # smallest -> largest
    if eig[-1] <= 0:
        return np.nan
    return float(max(eig[0], 0) / eig[-1])

