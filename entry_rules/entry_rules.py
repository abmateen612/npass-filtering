# ---- Helper: SMILES -> optimised 3D molecule ----
def make_3d(smiles, seed=42):
    """Convert a SMILES string into a 3D molecule with hydrogens.
    Returns None if the 3D structure cannot be built."""
    mol = Chem.MolFromSmiles(smiles)              # read SMILES into an RDKit molecule
    if mol is None:                               # invalid SMILES -> skip
        return None
    mol = largest_fragment(mol)                   # remove salts / counter-ions
    mol = Chem.AddHs(mol)                         # add hydrogens (essential for docking)

    params = AllChem.ETKDGv3()                    # modern 3D coordinate generator
    params.randomSeed = seed                      # fixed seed -> same result every run
    params.maxIterations = 200                    # stops hard molecules from hanging

    if AllChem.EmbedMolecule(mol, params) != 0:   # 0 = success, anything else = failed
        params.useRandomCoords = True             # second attempt with random start
        if AllChem.EmbedMolecule(mol, params) != 0:
            return None                           # give up on this compound
    try:
        AllChem.MMFFOptimizeMolecule(mol, maxIters=1000)   # relax the geometry
    except Exception:
        pass                                      # keep unoptimised structure if MMFF fails
    return mol

