from meeko import MoleculePreparation, PDBQTWriterLegacy

# Default settings: assigns Gasteiger charges, detects rotatable bonds, sets atom types
preparator = MoleculePreparation()

pdbqt_ok, pdbqt_failed = [], []                   # track successes and failures

for name in tqdm(ok_ids):
    try:
        # Read the 3D molecule back from its SDF (removeHs=False keeps the hydrogens)
        mol = Chem.MolFromMolFile(f"{SDF_DIR}{name}.sdf", removeHs=False)

        # Build the docking model (charges, torsion tree, atom types)
        setups = preparator.prepare(mol)

        # Turn the model into PDBQT text; returns (text, success flag, error message)
        pdbqt_string, is_ok, err = PDBQTWriterLegacy.write_string(setups[0])
        if not is_ok:
            raise RuntimeError(err)               # jump to the except block below

        # Save one .pdbqt file per compound
        with open(f"{PDBQT_DIR}{name}.pdbqt", "w") as f:
            f.write(pdbqt_string)

        pdbqt_ok.append(name)                     # remember it worked (used by Cell 14)
    except Exception as e:
        pdbqt_failed.append((name, str(e)[:80]))  # store ID + short error message

