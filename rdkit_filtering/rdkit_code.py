# Setup: imports, paths and a small helper that writes the summary file
from rdkit import Chem, __version__ as rdkit_version
from rdkit.Chem import Descriptors, Lipinski, rdMolDescriptors, FilterCatalog
from pathlib import Path
import pandas as pd

input_file = Path("/content/drive/MyDrive/npass_library/npass/npass_compounds.txt")
output_folder = Path("/content/drive/MyDrive/npass_library/results")
output_folder.mkdir(parents=True, exist_ok=True)
summary_file = output_folder / "pipeline_summary.txt"

def add_summary(lines):
    with open(summary_file, "a", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

# Read the file and remove compounds whose SMILES RDKit cannot read
df = pd.read_csv(input_file, sep=None, engine="python")
# df = df.head(100)   # remove the first # to test on 100 compounds first
total = len(df)

df["mol"] = [Chem.MolFromSmiles(str(smi)) for smi in df["SMILES"]]
before = len(df)
df = df[df["mol"].notna()]

summary_file.write_text("NPASS PIPELINE SUMMARY\nRDKit version: " + rdkit_version + "\n\n", encoding="utf-8")
add_summary(["Total compounds in input: " + str(total),
             "Invalid SMILES  removed: " + str(before - len(df)) + "  left: " + str(len(df))])
print("Total:", total, "| invalid removed:", before - len(df), "| left:", len(df))

# Remove duplicates: same canonical SMILES (different spellings of one molecule count as the same), first one kept
before = len(df)
df["Canonical_SMILES"] = [Chem.MolToSmiles(m) for m in df["mol"]]
df = df.drop_duplicates(subset="Canonical_SMILES", keep="first")

add_summary(["Duplicates  removed: " + str(before - len(df)) + "  left: " + str(len(df))])
print("Duplicates removed:", before - len(df), "| left:", len(df))

# Lipinski rule of five: MW > 500, LogP > 5, HBD > 5, HBA > 10 (each is a violation, NO violation allowed)
MAX_MW, MAX_LOGP, MAX_HBD, MAX_HBA = 500, 5, 5, 10
MAX_VIOLATIONS = 0

before = len(df)
df["MW"] = [round(Descriptors.MolWt(m), 3) for m in df["mol"]]
df["LogP"] = [round(Descriptors.MolLogP(m), 4) for m in df["mol"]]
df["HBD"] = [Lipinski.NumHDonors(m) for m in df["mol"]]
df["HBA"] = [Lipinski.NumHAcceptors(m) for m in df["mol"]]

break_mw = df["MW"] > MAX_MW
break_logp = df["LogP"] > MAX_LOGP
break_hbd = df["HBD"] > MAX_HBD
break_hba = df["HBA"] > MAX_HBA
df["Lipinski_violations"] = (break_mw.astype(int) + break_logp.astype(int)
                             + break_hbd.astype(int) + break_hba.astype(int))

rule_counts = ("MW " + str(int(break_mw.sum())) + ", LogP " + str(int(break_logp.sum()))
               + ", HBD " + str(int(break_hbd.sum())) + ", HBA " + str(int(break_hba.sum())))
df = df[df["Lipinski_violations"] <= MAX_VIOLATIONS]

add_summary(["Lipinski (violations allowed: " + str(MAX_VIOLATIONS) + ")  removed: " + str(before - len(df))
             + "  left: " + str(len(df)) + "   (compounds breaking each rule: " + rule_counts + ")"])
print("Lipinski removed:", before - len(df), "| left:", len(df), "|", rule_counts)

# Torsion (rotatable) bond filter: keep only compounds with fewer than 10 rotatable bonds
MAX_ROT_BONDS = 10     # compounds with 10 or more rotatable bonds are removed

before = len(df)
df["Rotatable_Bonds"] = [Lipinski.NumRotatableBonds(m) for m in df["mol"]]
df = df[df["Rotatable_Bonds"] < MAX_ROT_BONDS]

add_summary(["Rotatable bonds (< " + str(MAX_ROT_BONDS) + ")  removed: " + str(before - len(df))
             + "  left: " + str(len(df))])
print("Rotatable bonds removed:", before - len(df), "| left:", len(df))

# PAINS filter (A + B + C): remove compounds with assay-interference substructures
before = len(df)
params = FilterCatalog.FilterCatalogParams()
params.AddCatalog(FilterCatalog.FilterCatalogParams.FilterCatalogs.PAINS)
pains = FilterCatalog.FilterCatalog(params)

df = df[[not pains.HasMatch(m) for m in df["mol"]]]

add_summary(["PAINS  removed: " + str(before - len(df)) + "  left: " + str(len(df))])
print("PAINS removed:", before - len(df), "| left:", len(df))

# ADMET: first predict the properties for all remaining compounds, then filter one by one
from admet_ai import ADMETModel

df = df.reset_index(drop=True)
model = ADMETModel()
preds = model.predict(smiles=df["Canonical_SMILES"].tolist()).reset_index(drop=True)
preds = preds.drop(columns=[c for c in preds.columns if c.endswith("_drugbank_approved_percentile")])
df = pd.concat([df, preds.drop(columns=[c for c in preds.columns if c in df.columns])], axis=1)

if "TPSA" not in df.columns:                       # TPSA is calculated directly from the structure
    df["TPSA"] = [round(rdMolDescriptors.CalcTPSA(m), 2) for m in df["mol"]]

# (column name, "max" keeps value <= cutoff / "min" keeps value >= cutoff, cutoff, text)
admet_filters = [
    ("Solubility_AqSolDB",        "min", -5,  "logS >= -5"),
    ("Lipophilicity_AstraZeneca", "max", 5,   "Lipophilicity <= 5"),
    ("TPSA",                      "max", 140, "TPSA <= 140"),
    ("AMES",                      "max", 0.5, "Ames <= 0.5"),
    ("Carcinogens_Lagunin",       "max", 0.5, "Carcinogenicity <= 0.5"),
    ("Pgp_Broccatelli",           "max", 0.5, "Pgp <= 0.5"),
    ("CYP2D6_Veith",              "max", 0.5, "CYP2D6 inhibition <= 0.5"),
    ("CYP3A4_Veith",              "max", 0.5, "CYP3A4 inhibition <= 0.5"),
    ("hERG",                      "max", 0.5, "hERG <= 0.5"),
    ("DILI",                      "max", 0.5, "DILI <= 0.5"),
    ("PPBR_AZ",                   "max", 90,  "PPB <= 90"),
    ("HIA_Hou",                   "min", 0.5, "HIA >= 0.5 (good absorption)"),
]

missing = [f[0] for f in admet_filters if f[0] not in df.columns]
if missing:
    raise SystemExit("These ADMET columns are not found: " + str(missing)
                     + "\nAvailable columns: " + str(df.columns.tolist()))

lines = []
for name, rule, cutoff, text in admet_filters:
    before = len(df)
    df = df[df[name] <= cutoff] if rule == "max" else df[df[name] >= cutoff]
    lines.append("ADMET " + text + "  removed: " + str(before - len(df)) + "  left: " + str(len(df)))

add_summary(lines)
print("\n".join(lines))
print("Compounds after ADMET:", len(df))































































